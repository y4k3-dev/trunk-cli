require("lfs")

---Parses a gitignore into a list of Lua patterns for matching files and directories.
---@param ignore_path string The file path to the .gitignore file.
---@return table A list of parsed Lua string patterns.
local function parseGitIgnore(ignore_path)
    local patterns = { "^%.git$" } 
    
    local file = io.open(ignore_path, "r")
    if not file then return patterns end

    for line in file:lines() do
        line = line:match("^%s*(.-)%s*$")

        if line ~= "" and line:sub(1, 1) ~= "#" then
            line = line:gsub("/$", "")
            line = line:gsub("^/", "")
            
            -- Escape magic characters
            local pattern = line:gsub("([%^%$%(%)%%%.%[%]%+%-%?])", "%%%1")
            pattern = pattern:gsub("%*", ".*")
            pattern = "^" .. pattern .. "$"
            
            table.insert(patterns, pattern)
        end
    end
    
    file:close()
    return patterns
end

---Recursively builds a tree of files and directories, respecting ignore patterns.
---@param path string The target directory to scan.
---@param name string|nil The display name for the current folder.
---@param is_root boolean Whether this is the top-level directory.
---@param ignore_patterns table List of string patterns to ignore.
---@return table A nested table representing the file structure.
local function getFileTree(path, name, is_root, ignore_patterns)
    name = name or path:match("([^/\\]+)$") or "root"
    
    local node = {
        name = name,
        type = "folder",
        children = {}
    }
    
    if is_root then
        node.is_root = true
    end

    for file in lfs.dir(path) do
        if file ~= "." and file ~= ".." then
            
            local ignored = false
            for _, pattern in ipairs(ignore_patterns) do
                if file:match(pattern) then
                    ignored = true
                    break
                end
            end
            
            if not ignored then
                local full_path = path .. "/" .. file
                local mode = lfs.attributes(full_path, "mode")
                
                if mode == "directory" then
                    local child_node = getFileTree(full_path, file, false, ignore_patterns)
                    table.insert(node.children, child_node)
                elseif mode == "file" then
                    table.insert(node.children, {
                        name = file,
                        type = "file"
                    })
                end
            end
        end
    end

    table.sort(node.children, function(a, b)
        if a.type ~= b.type then
            return a.type == "folder"
        end
        return a.name:lower() < b.name:lower()
    end)
    
    return node
end

---Copies text directly to the Windows clipboard forcing UTF-8 encoding.
---@param text string The text to copy.
local function copyToClipboard(text)
    local pipe = io.popen("chcp 65001 > NUL && clip", "w")
    if pipe then
        pipe:write(text)
        pipe:close()
        print("\n[+] Successfully copied tree to clipboard!")
    else
        print("\n[-] Error: Could not access the clipboard.")
    end
end

---Generates the formatted string representation of the file tree.
---@param node table The node object generated by getFileTree.
---@param prefix string|nil The indentation string for the current recursive depth.
---@return string The final formatted tree string.
local function craftTree(node, prefix)
    prefix = prefix or ""
    local tree = ""

    if prefix == "" then
        local clean_name = node.name:gsub("^%s*(.-)%s*$", "%1")
        tree = tree .. clean_name .. "/\n"
    end

    local child_count = node.children and #node.children or 0

    for i, child in ipairs(node.children) do
        local is_last = (i == child_count)
        local branch = is_last and "└── " or "├── "
        local next_prefix = prefix .. (is_last and "    " or "│   ")

        if child.type == "folder" then
            tree = tree .. prefix .. branch .. child.name .. "/\n"
            tree = tree .. craftTree(child, next_prefix)
        else
            tree = tree .. prefix .. branch .. child.name .. "\n"
        end
    end

    return tree
end

---Main entry point. Orchestrates the scanning, formatting, and copying.
---@param path string|nil The target directory path provided via CLI.
local function Main(path)
    path = path or "."

    local clean_path = path:gsub("[/\\]+$", "")
    local root_name = clean_path:match("([^/\\]+)$") or "root"

    local gitignore_path = clean_path .. "/.gitignore"
    local ignore_rules = parseGitIgnore(gitignore_path)

    local tree = getFileTree(clean_path, root_name, true, ignore_rules)
    local output = craftTree(tree)
    
    print(output)
    copyToClipboard(output)
end

Main(arg[1])